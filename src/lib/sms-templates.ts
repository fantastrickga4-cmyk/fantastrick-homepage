// 쓰는 문자 종류. confirm 은 사장님이 입금 없이 확정할 때(전화예약 등) 나가는 확정 안내다.
export type SmsType = "payment" | "confirm";

// 발송 내역에는 **이제 안 쓰는 종류**(reminder·reservation·cancel·admin_cancel)의 옛 기록이
// 남아 있다. 그 기록에 [다시 보내기] 를 눌러도 나가지 않게 막는 데 쓴다.
export const ACTIVE_SMS_TYPES: readonly SmsType[] = ["payment", "confirm"];
export function isActiveSmsType(t: string): t is SmsType {
  return (ACTIVE_SMS_TYPES as readonly string[]).includes(t);
}

